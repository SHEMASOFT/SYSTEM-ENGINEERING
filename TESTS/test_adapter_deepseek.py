"""DeepSeek Harness adapter: rendered structure and model propagation.

Hermetic: every test builds a temporary canonical tree, so nothing depends on
the repository's own contracts or on a DSH installation.
"""

from __future__ import annotations

import json
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import support  # noqa: E402,F401  (puts SCRIPTS/ on sys.path)

from se_core import runtimes  # noqa: E402

HEADER = "Generated by `se adapter deepseek`"

AGENTS = (
    {
        "id": "AG-0001",
        "version": "1.0.0",
        "name": "analyst",
        "description": "Analyze discovery output and formalize requirements.",
        "purpose": "Analyze discovery output and formalize requirements.",
        "gate_responsibility": ["G1"],
        "capabilities": [{"name": "requirements", "description": "Write typed requirements."}],
        "restrictions": ["Must not invent requirements without a stated source."],
        "permissions": ["READ"],
    },
    {
        "id": "AG-0002",
        "version": "1.0.0",
        "name": "reviewer",
        "description": "Independently review artifacts and evidence.",
        "purpose": "Independently review artifacts and evidence.",
        "gate_responsibility": ["G5"],
        "capabilities": [{"name": "review", "description": "Record findings."}],
        "restrictions": ["Must not review work it authored."],
        "permissions": ["READ", "WRITE_DOCS"],
    },
)

SKILL = (
    "---\n"
    "name: impl-tdd\n"
    "description: Test-first implementation.\n"
    "---\n"
    "\n"
    "# impl-tdd\n"
    "\n"
    "Write the test first.\n"
)


def build_contracts(base: Path, model: str | None = None) -> Path:
    """Write a minimal canonical tree the adapters can render."""
    root = base / "contracts"
    for agent in AGENTS:
        target = root / "AGENTS" / agent["name"]
        target.mkdir(parents=True, exist_ok=True)
        (target / "agent.json").write_text(json.dumps(agent, indent=2) + "\n", encoding="utf-8")
    (root / "COMMANDS").mkdir()
    (root / "COMMANDS" / "commands.json").write_text(
        json.dumps(
            {
                "schema_version": "1",
                "commands": [
                    {
                        "name": "plan",
                        "purpose": "Decompose requirements into tasks.",
                        "description": "Decompose requirements into tasks.",
                        "execution_intent": "READ_ONLY",
                        "risk_level": "LOW",
                        "gate": "G2",
                    }
                ],
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    skill = root / "SKILLS" / "impl-tdd"
    skill.mkdir(parents=True)
    (skill / "SKILL.md").write_text(SKILL, encoding="utf-8")
    if model is not None:
        # Parse provider/model and write in the format the resolver expects
        if "/" in model:
            provider, model_id = model.split("/", 1)
        else:
            provider, model_id = "openai", model
        (root / "opencode.jsonc").write_text(
            json.dumps({"provider": provider, "model": model_id}, indent=2) + "\n",
            encoding="utf-8",
        )
    return root


def render(base: Path, model: str | None = None) -> tuple[Path, dict]:
    root = build_contracts(base, model=model)
    out = base / "out"
    result = runtimes.generate_deepseek(root, out)
    return out, result


def read(out: Path, rel: str) -> str:
    return (out / rel).read_text(encoding="utf-8")


class DeepseekStructureTests(unittest.TestCase):
    def test_tree_matches_the_runtime_layout(self):
        with tempfile.TemporaryDirectory() as tmp:
            out, result = render(Path(tmp))
            self.assertEqual(result["status"], "PASS")
            paths = {f["path"] for f in result["files"]}
            self.assertIn("AGENTS.local.md", paths)
            self.assertIn(".dsh/se.patch.yml", paths)
            self.assertIn(".dsh/skills/impl-tdd/SKILL.md", paths)

    def test_it_does_not_claim_the_shared_agents_file(self):
        with tempfile.TemporaryDirectory() as tmp:
            out, _ = render(Path(tmp))
            self.assertFalse((out / "AGENTS.md").exists())
            self.assertTrue((out / "AGENTS.local.md").exists())

    def test_every_generated_file_carries_the_provenance_header(self):
        with tempfile.TemporaryDirectory() as tmp:
            out, result = render(Path(tmp))
            for entry in result["files"]:
                self.assertIn(HEADER, read(out, entry["path"]), entry["path"])

    def test_patch_declares_one_preset_per_role(self):
        with tempfile.TemporaryDirectory() as tmp:
            out, _ = render(Path(tmp))
            patch = read(out, ".dsh/se.patch.yml")
            self.assertIn("- insert:", patch)
            for role in ("analyst", "reviewer"):
                self.assertIn(f"    - id: preset-{role}", patch)
            self.assertIn("name: '@deepseek-ai/dsh-agent-preset'", patch)
            self.assertIn("id: persona", patch)
            self.assertIn("name: '@deepseek-ai/dsh-persona'", patch)
            self.assertIn("prefix: |-", patch)
            # The role contract is the persona body, not just its description.
            self.assertIn("Must not invent requirements without a stated source.", patch)

    def test_patch_parses_as_yaml(self):
        """A patch DSH cannot load is a failed install, not a formatting nit."""
        import yaml

        with tempfile.TemporaryDirectory() as tmp:
            out, _ = render(Path(tmp), model="openai/gpt-4o")
            document = yaml.safe_load(read(out, ".dsh/se.patch.yml"))
            self.assertIsInstance(document, list)
            rows = document[0]["insert"]
            presets = {row["config"]["id"]: row for row in rows if row["id"].startswith("preset-")}
            self.assertIn("analyst", presets)
            self.assertEqual(presets["analyst"]["name"], "@deepseek-ai/dsh-agent-preset")
            self.assertEqual(presets["analyst"]["config"]["order"], 1)
            self.assertTrue(presets["analyst"]["config"]["plugins"])

    def test_presets_load_project_instructions_and_the_skill_surface(self):
        with tempfile.TemporaryDirectory() as tmp:
            out, _ = render(Path(tmp))
            patch = read(out, ".dsh/se.patch.yml")
            self.assertIn("name: '@deepseek-ai/dsh-agent-instructions'", patch)
            self.assertIn("maxBytes: 65536", patch)
            self.assertIn("name: '@deepseek-ai/dsh-skill-filesystem'", patch)
            self.assertIn("name: '@deepseek-ai/dsh-tool-skill'", patch)

    def test_skill_keeps_frontmatter_first_and_gains_the_header_after_it(self):
        with tempfile.TemporaryDirectory() as tmp:
            out, _ = render(Path(tmp))
            text = read(out, ".dsh/skills/impl-tdd/SKILL.md")
            self.assertTrue(text.startswith("---\nname: impl-tdd\ndescription: "))
            closing = text.index("\n---\n", 4)
            self.assertLess(closing, text.index(HEADER))
            self.assertIn("Write the test first.", text)

    def test_instructions_roster_lists_roles_commands_and_servers(self):
        with tempfile.TemporaryDirectory() as tmp:
            out, _ = render(Path(tmp))
            text = read(out, "AGENTS.local.md")
            self.assertIn("## Roles", text)
            self.assertIn("**analyst**", text)
            self.assertIn("## Commands", text)
            self.assertIn("**plan**", text)
            self.assertIn("## MCP servers", text)


class DeepseekModelTests(unittest.TestCase):
    def test_model_is_carried_when_configured(self):
        with tempfile.TemporaryDirectory() as tmp:
            out, _ = render(Path(tmp), model="openai/gpt-4o")
            patch = read(out, ".dsh/se.patch.yml")
            self.assertIn("# model: openai/gpt-4o", patch)
            # Every role resolves to the same route, so it is also the deployment default.
            self.assertIn("- id: agent-default-model", patch)
            self.assertIn("name: '@deepseek-ai/dsh-agent-default-model'", patch)
            self.assertIn("provider: openai", patch)
            self.assertIn("model: gpt-4o", patch)
            self.assertIn("openai/gpt-4o", read(out, "AGENTS.local.md"))

    def test_no_model_is_invented_when_none_is_configured(self):
        with tempfile.TemporaryDirectory() as tmp:
            out, _ = render(Path(tmp), model=None)
            patch = read(out, ".dsh/se.patch.yml")
            self.assertNotIn("agent-default-model", patch)
            self.assertNotIn("# model:", patch)
            self.assertNotIn("openai/gpt-4o", patch)
            instructions = read(out, "AGENTS.local.md")
            self.assertIn("No model is configured, so none is invented", instructions)

    def test_contract_model_wins_over_the_harness_selection(self):
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            root = build_contracts(base, model="openai/gpt-4o")
            agent_path = root / "AGENTS" / "reviewer" / "agent.json"
            agent = json.loads(agent_path.read_text(encoding="utf-8"))
            agent["llm_config"] = {"provider": "anthropic", "model": "claude-haiku"}
            agent_path.write_text(json.dumps(agent, indent=2) + "\n", encoding="utf-8")
            out = base / "out"
            runtimes.generate_deepseek(root, out)
            patch = read(out, ".dsh/se.patch.yml")
            self.assertIn("# model: anthropic/claude-haiku", patch)
            self.assertIn("# model: openai/gpt-4o", patch)
            # The roles no longer agree, so no process-wide default is written.
            self.assertNotIn("agent-default-model", patch)

    def test_a_model_without_provider_is_recorded_but_not_used_as_a_default(self):
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            root = build_contracts(base)
            for agent in AGENTS:
                path = root / "AGENTS" / agent["name"] / "agent.json"
                data = json.loads(path.read_text(encoding="utf-8"))
                data["llm_config"] = {"model": "sonnet"}
                path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
            out = base / "out"
            runtimes.generate_deepseek(root, out)
            patch = read(out, ".dsh/se.patch.yml")
            self.assertIn("# model: sonnet", patch)
            self.assertNotIn("agent-default-model", patch)


class DeepseekGenerationTests(unittest.TestCase):
    def test_generation_is_idempotent(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = build_contracts(Path(tmp), model="openai/gpt-4o")
            out = Path(tmp) / "out"
            runtimes.generate_deepseek(root, out)
            second = runtimes.generate_deepseek(root, out)
            self.assertEqual({f["action"] for f in second["files"]}, {"unchanged"})

    def test_dry_run_plans_without_writing(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = build_contracts(Path(tmp))
            out = Path(tmp) / "out"
            result = runtimes.generate_deepseek(root, out, dry_run=True)
            self.assertEqual({f["action"] for f in result["files"]}, {"write"})
            self.assertFalse(out.exists())

    def test_cli_dry_run_writes_nothing(self):
        with tempfile.TemporaryDirectory() as tmp:
            code, output = support.run_cli("adapter", "deepseek", "--output", tmp, "--dry-run")
            self.assertEqual(code, 0, output)
            self.assertIn("Status: PASS", output)
            self.assertEqual(list(Path(tmp).rglob("*")), [])

    def test_cli_all_generates_the_deepseek_layer_too(self):
        with tempfile.TemporaryDirectory() as tmp:
            code, output = support.run_cli("adapter", "all", "--output", tmp)
            self.assertEqual(code, 0, output)
            self.assertIn("Adapters: claude-code, codex, deepseek", output)
            self.assertTrue((Path(tmp) / ".dsh" / "se.patch.yml").exists())
            self.assertTrue((Path(tmp) / "AGENTS.local.md").exists())
            # The Codex adapter still owns the shared AGENTS.md.
            self.assertTrue((Path(tmp) / "AGENTS.md").exists())


if __name__ == "__main__":
    unittest.main()

